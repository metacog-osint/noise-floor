#!/usr/bin/env python3
"""validate_latching.py — does the v1.3 latching tag explain downstream "interference"?

  1. Latched aircraft per day, and latched share of gross-bad aircraft-hexes by area
  2. Where latched episodes began (onset regions, all days pooled)
  3. Nightly central-Europe bursts (01-06Z): v1.2 analysis (raw counts) vs v1.3 (live counts)
  4. Hotspot shares, raw vs live (they should barely move)
  5. Map: latched aircraft-hexes and onset regions for one day

Run pipeline/pnt_analysis.py on the days first (v1.3 data); v1.2 analysis outputs must be in data/pnt/analysis_v12.
Writes docs/validation/latching_results.md and docs/validation/img/latching_*.png.
"""
import argparse, json, os, sys
from collections import Counter
from datetime import date, timedelta

import h3
import pyarrow.parquet as pq

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from validate_phase1 import CACHE, ROOT, SUBREGIONS, country, in_box  # noqa: E402

DAILY = os.path.join(ROOT, "data", "pnt", "daily")
AN13 = os.path.join(ROOT, "data", "pnt", "analysis")
AN12 = os.path.join(ROOT, "data", "pnt", "analysis_v12")
OUT_MD = os.path.join(ROOT, "docs", "validation", "latching_results.md")
IMG = os.path.join(ROOT, "docs", "validation", "img")
CENTRAL_EUROPE = (45.0, 55.0, 5.0, 25.0)
AREAS = {"Central Europe (45–55N, 5–25E)": CENTRAL_EUROPE, "Western Europe (43–55N, 10W–5E)": (43.0, 55.0, -10.0, 5.0),
         "Baltic (53.5–61N, 17–30E)": (53.5, 61.0, 17.0, 30.0), "Black Sea (40.5–47.5N, 27–42E)": (40.5, 47.5, 27.0, 42.0),
         "North America (25–55N, 125–65W)": (25.0, 55.0, -125.0, -65.0)}


def days(spec):
    out = []
    for s in spec:
        if ":" in s:
            a, b = (date.fromisoformat(x) for x in s.split(":"))
            while a <= b:
                out.append(a.isoformat()); a += timedelta(days=1)
        else:
            out.append(s)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("days", nargs="+")
    ap.add_argument("--map-day", required=True)
    a = ap.parse_args()
    ds = days(a.days)
    md = ["# Latching tag (processor v1.3): generated results", "", "Generated by `tools/validate_latching.py`. Narrative: `phase1.md` (latching section).", ""]

    # 1. per day, by area
    md += ["## 1. Latched aircraft and latched share of gross-bad aircraft-hexes", "",
           "| Day | Latched aircraft | Unjudged candidate cells | " + " | ".join(AREAS) + " |", "|---|---|---|" + "---|" * len(AREAS)]
    onsets = Counter()
    for d in ds:
        s = json.load(open(os.path.join(DAILY, f"{d}.summary.json")))
        lt = s.get("latching") or {}
        for c, la, lo, n in lt.get("latch_onset_regions_res2", []):
            onsets[(c, la, lo)] += n
        rows = pq.read_table(os.path.join(DAILY, f"{d}.parquet")).to_pylist()
        cells = []
        for box in AREAS.values():
            sel = [r for r in rows if in_box(r, box)]
            bad = sum(r["bad_nacp"] for r in sel); lat = sum(r["latched"] for r in sel)
            cells.append(f"{100 * lat / bad:.0f}% ({lat}/{bad})" if bad else "–")
        md.append(f"| {d} | {lt.get('latched_aircraft', '–')} | {lt.get('latch_candidate_cells_unjudged', '–')} | " + " | ".join(cells) + " |")

    # 2. onsets (top 30 entries per day were kept; pooled here)
    md += ["", "## 2. Where latched episodes began (H3 res-2 regions, all days pooled)", "",
           "| Rank | Region centre | Country | Latched aircraft |", "|---|---|---|---|"]
    for i, ((c, la, lo), n) in enumerate(onsets.most_common(20), 1):
        md.append(f"| {i} | {la}, {lo} | {country(la, lo)} | {n} |")
    in_hot = sum(n for (c, la, lo), n in onsets.items() if any(in_box({"lat": la, "lon": lo}, b) for k, b in SUBREGIONS.items()
                                                                 if not k.startswith(("Cyprus", "High latitude"))))
    md += ["", f"Onsets inside the Phase 1 hotspot sub-regions: {in_hot} of {sum(onsets.values())} "
           f"({100 * in_hot / max(1, sum(onsets.values())):.0f}%)."]

    # 3. nightly central-Europe bursts, v1.2 vs v1.3
    md += ["", "## 3. Burst events over central Europe starting 01–06Z: v1.2 (raw) vs v1.3 (live)", "",
           "| Day | v1.2 events | v1.3 events | v1.2 largest peak | v1.3 largest peak |", "|---|---|---|---|---|"]
    tot12 = tot13 = 0
    for d in ds:
        res = []
        for base in (AN12, AN13):
            p = os.path.join(base, f"{d}.bursts.json")
            ev = (json.load(open(p)).get("events", []) if os.path.exists(p) else [])
            ce = [e for e in ev if in_box(e, CENTRAL_EUROPE) and 1 <= int(e["start"][:2]) < 6]
            res.append(ce)
        tot12 += len(res[0]); tot13 += len(res[1])
        md.append(f"| {d} | {len(res[0])} | {len(res[1])} | {max((e['peak_aircraft'] for e in res[0]), default='–')} | "
                  f"{max((e['peak_aircraft'] for e in res[1]), default='–')} |")
    md.append(f"| **Total** | **{tot12}** | **{tot13}** | | |")

    # 4. hotspot shares raw vs live
    md += ["", "## 4. Hotspot shares, raw vs live (share of aircraft-hexes worse than 93 m)", "",
           "| Sub-region | " + " | ".join(f"{d} raw → live" for d in ds[-3:]) + " |", "|---|" + "---|" * 3]
    for name, box in SUBREGIONS.items():
        cells = []
        for d in ds[-3:]:
            rows = [r for r in pq.read_table(os.path.join(DAILY, f"{d}.parquet")).to_pylist() if in_box(r, box)]
            ac = sum(r["aircraft"] for r in rows)
            cells.append(f"{100 * sum(r['bad_nacp'] for r in rows) / ac:.1f} → {100 * sum(r['bad_nacp_live'] for r in rows) / ac:.1f}" if ac else "–")
        md.append(f"| {name} | " + " | ".join(cells) + " |")

    # 5. map
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.collections import PolyCollection
    rows = pq.read_table(os.path.join(DAILY, f"{a.map_day}.parquet")).to_pylist()
    s = json.load(open(os.path.join(DAILY, f"{a.map_day}.summary.json")))
    x0, x1, y0, y1 = -15, 62, 22, 72
    fig, ax = plt.subplots(figsize=(11, 9), dpi=110)
    land = json.load(open(os.path.join(CACHE, "ne_50m_land.geojson"), encoding="utf-8"))
    for f in land["features"]:
        g = f["geometry"]; polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for p in polys:
            xs, ys = zip(*p[0]); ax.fill(xs, ys, color="#eceae4", lw=0, zorder=0)
    live, lat = [], []
    for r in rows:
        if not (x0 - 5 <= r["lon"] <= x1 + 5 and y0 - 5 <= r["lat"] <= y1 + 5):
            continue
        b = [(lo, la) for la, lo in h3.cell_to_boundary(r["h3"])]
        if r["bad_nacp_live"] >= 2:
            live.append(b)
        elif r["latched"] >= 1:
            lat.append(b)
    ax.add_collection(PolyCollection(live, facecolors="#d7301f", edgecolors="none", alpha=0.8, zorder=1))
    ax.add_collection(PolyCollection(lat, facecolors="#3182bd", edgecolors="none", alpha=0.8, zorder=1))
    for c, la, lo, n in s["latching"]["latch_onset_regions_res2"]:
        if x0 <= lo <= x1 and y0 <= la <= y1:
            ax.scatter([lo], [la], s=12 + 6 * n, facecolors="none", edgecolors="#111", lw=1.2, zorder=2)
    ax.set_xlim(x0, x1); ax.set_ylim(y0, y1); ax.set_aspect(1.6); ax.set_xticks([]); ax.set_yticks([])
    ax.set_title(f"{a.map_day}: live degradation (red: hexes with ≥ 2 live gross-bad aircraft) vs latched only (blue)\n"
                 "circles: where latched episodes began (size ~ aircraft)", fontsize=10)
    ax.text(0.005, 0.005, "Data: adsb.lol (ODbL 1.0) · Basemap: Natural Earth · Method: docs/method-card.md (v1.3)",
            transform=ax.transAxes, fontsize=8, color="#444")
    os.makedirs(IMG, exist_ok=True)
    fig.savefig(os.path.join(IMG, f"latching_{a.map_day}.png"), bbox_inches="tight"); plt.close(fig)
    md += ["", f"## 5. Map, {a.map_day}", "", f"![Latching map](img/latching_{a.map_day}.png)"]
    open(OUT_MD, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(f"wrote {OUT_MD}")


if __name__ == "__main__":
    main()
