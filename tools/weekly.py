#!/usr/bin/env python3
"""weekly.py: draft the weekly assessment from the site's own public data (the folded daily-status lane's weekly product).

  python tools/weekly.py [--end 2026-10-25] [--out products/]

Reads only what the public site serves (board.json, trend.json, gnss/days.json, events/<day>.json, geo.json,
events-monthly.json, vessels/gnss_at_sea.json) plus NOAA SWPC's planetary K-index. Writes
products/<end>-weekly-draft.md for a person to review: a draft, never published by this script. Times UTC; Central time
named where a time of day matters. Every number comes from a file it cites; the judgments are left to the reviewer.
"""
import argparse
import json
import math
import os
import statistics
import urllib.request
from datetime import date, datetime, timedelta, timezone
from zoneinfo import ZoneInfo

CT = ZoneInfo("America/Chicago")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://noisefloor.theintelligence.company"
UA = {"User-Agent": "noise-floor weekly (github.com/metacog-osint/noise-floor)"}
KP_URL = "https://services.swpc.noaa.gov/products/noaa-planetary-k-index.json"


def get(path):
    url = path if path.startswith("http") else f"{SITE}{path}"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
            return json.load(r)
    except Exception:
        return None


def mean(xs):
    xs = [x for x in xs if x is not None]
    return statistics.mean(xs) if xs else None


def fmt(x, nd=1):
    return "n/a" if x is None else f"{x:.{nd}f}"


def central(t):
    """'HH:MM CDT' (or CST) for a UTC datetime."""
    c = t.astimezone(CT)
    return f"{c:%H:%M} {c.tzname()}"


class Places:
    def __init__(self):
        pl = (get("/data/places.json") or {}).get("places", [])
        self.pl = [p for p in pl if len(p) > 3 and p[3] <= 5]

    def near(self, lat, lon, limit=350):
        best, name = limit, None
        for p in self.pl:
            p1, p2 = math.radians(lat), math.radians(p[1])
            x = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(p[2] - lon) / 2) ** 2
            d = 12742 * math.asin(min(1.0, math.sqrt(x)))
            if d < best:
                best, name = d, p[0]
        return name


def ll(lat, lon):
    return f"{abs(lat):.1f}°{'N' if lat >= 0 else 'S'} {abs(lon):.1f}°{'E' if lon >= 0 else 'W'}"


def draft(end):
    d_end = date.fromisoformat(end)
    week = [(d_end - timedelta(days=k)).isoformat() for k in range(6, -1, -1)]
    board, trend, days = get("/data/board.json") or {}, get("/data/trend.json"), get("/data/gnss/days.json") or []
    geo, em, sea, kp = get("/data/geo.json"), get("/data/events-monthly.json"), get("/data/vessels/gnss_at_sea.json"), get(KP_URL)
    lines = [f"# Noise Floor weekly: {week[0]} to {week[-1]} (UTC)", "",
             "**DRAFT for review, not published.** Generated by `tools/weekly.py` from the public site's data on "
             f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC ({central(datetime.now(timezone.utc))}). Numbers are from the files cited; the judgments are the "
             "reviewer's. Grades describe evidence, never attribution.", ""]

    # GNSS from aircraft
    dmap = {d["day"]: d for d in days}
    jw = [dmap[d]["jam_hexes"] for d in week if d in dmap]
    prior = [dmap[(d_end - timedelta(days=k)).isoformat()]["jam_hexes"] for k in range(7, 35) if (d_end - timedelta(days=k)).isoformat() in dmap]
    rows = []
    if trend:
        idx = {d: i for i, d in enumerate(trend["days"])}
        for name, r in trend["regions"].items():
            sh = r["share"]
            wk = mean([sh[idx[d]] for d in week if d in idx])
            base = mean([sh[idx[(d_end - timedelta(days=k)).isoformat()]] for k in range(7, 35) if (d_end - timedelta(days=k)).isoformat() in idx])
            rows.append((name, wk, base, None if wk is None or base is None else wk - base))
        rows.sort(key=lambda r: -(r[1] or 0))
    events = [get(f"/data/events/{d}.json") for d in week]
    major = []
    for ev in events:
        for e in (ev or {}).get("anomalies", []):
            if e.get("m") == "jam" and e.get("tier") == "major":
                major.append((ev["day"], e))
    loss = (board.get("loss") or {}).get("areas") or []
    ch = board.get("changes") or {}

    bl = []
    if jw and prior:
        bl.append(f"Hexes at jamming scale averaged {statistics.mean(jw):,.0f} a day this week against {statistics.mean(prior):,.0f} "
                  "over the four weeks before (aircraft, worldwide).")
    if rows:
        up = [r for r in rows if r[3] is not None and r[3] >= 5]
        dn = [r for r in rows if r[3] is not None and r[3] <= -5]
        if up or dn:
            bl.append("Known areas: " + "; ".join([f"{r[0]} up {r[3]:.1f} points" for r in up] + [f"{r[0]} down {abs(r[3]):.1f} points" for r in dn]) + ".")
    if loss and loss[0]["share"] >= 20:
        bl.append(f"Position loss on {board['loss']['day']}: {loss[0]['name']} {loss[0]['share']:g}% of aircraft heard sent no position, "
                  "so the degraded share there understates the interference.")
    sp = board.get("spoofing")
    if sp:
        bl.append(f"Spoofing from aircraft on {sp['day']}: {sp['active']} active episodes across {sp['aircraft']} aircraft.")
    lines += ["## Bottom line", ""] + [f"- {b}" for b in bl] + [""]

    lines += ["## GNSS interference from aircraft", ""]
    if rows:
        lines += ["| Area | This week (mean share) | Four weeks before | Change (points) |", "|---|---|---|---|"]
        lines += [f"| {n} | {fmt(w)}% | {fmt(b)}% | {fmt(c)} |" for n, w, b, c in rows]
        lines += ["", "Share of aircraft-hexes worse than 93 m (live counts), from `trend.json`. A fall can mean aircraft dropped out "
                  "of the count; read it beside position loss.", ""]
    if ch:
        lines += [f"Regions at jamming scale on {ch.get('day')}: {ch.get('regions_today')}; new this week {ch.get('new_count')}, ended "
                  f"{ch.get('ended_count')}, long-running {ch.get('long_running')} (`board.json`).", ""]
    if major:
        places = Places()
        top = sorted(major, key=lambda x: -(x[1].get("excess") or 0))[:12]
        lines += [f"The {len(top)} strongest of {len(major)} major jamming-scale anomaly events this week, by excess over the "
                  "area's usual level (daily event files; times UTC; A350/A380 share where the daily tables have it, from 25 Oct):", ""]
        for day, e in sorted(top, key=lambda x: (x[0], x[1]["h0"])):
            hs = f"; A350/A380 share {round(100 * e['hs'])}%" if e.get("hs") is not None else ""
            near = places.near(e["lat"], e["lon"])
            lines.append(f"- {day}, {e['h0']:02d}:00–{e['h1']:02d}:59Z: {e['peak']:.0f}% degraded around {ll(e['lat'], e['lon'])}"
                         + (f" (near {near})" if near else "") + f", {e['excess']:.0f} points above usual{hs}"
                         + (f"; fits announced test {e['test']}" if e.get("test") else ""))
        lines.append("")
    if loss:
        lines += [f"Position loss on {board['loss']['day']} (aircraft heard by MLAT but sending no position):", ""]
        lines += [f"- {a['name']}: {a['share']:g}% of {a['heard']:,} aircraft heard" for a in loss[:4]] + [""]

    lines += ["## Spoofing", ""]
    if sp:
        vic = ", ".join(f"near {v['near']} ({v['episodes']})" if v.get("near") else f"{ll(v['lat'], v['lon'])} ({v['episodes']})" for v in sp["victims"][:5])
        lines += [f"On {sp['day']}: {sp['active']} active episodes, {sp['aircraft']} aircraft. Where aircraft were: {vic}. "
                  "Spoofed-to places: " + "; ".join(f"{ll(p['lat'], p['lon'])} ({p['episodes']})" for p in sp["spoofed_to"][:3]) + ".", ""]
    else:
        lines += ["No daily spoofing summary yet.", ""]

    lines += ["## At sea (Finland's open AIS)", ""]
    if sea:
        top = max(sea.get("by_area") or [{}], key=lambda a: a.get("vessels", 0))
        lines += [f"{sea.get('affected_vessels')} ships showed GNSS interference in the last collection (built {str(sea.get('generated'))[:16]} UTC), "
                  f"most in {top.get('area')} ({top.get('vessels')}). The AIS method passed its held-out test on 26 Oct (regional; the "
                  "ships' own lost-fix check fell short at 2.6x against 3x).", ""]

    lines += ["## Declared and official", ""]
    dc = board.get("declared") or {}
    if dc.get("faa_tests"):
        lines.append(f"- Announced US GPS tests: {dc['faa_tests']['today']} on the build day, {dc['faa_tests']['next7']} in the following 7 days (FAA SPANS).")
    for n in dc.get("notices") or []:
        lines.append(f"- {n['id']} ({n['issuer']}): {n['area']}: “{n['wording']}”.")
    e = (board.get("easa") or {}).get("tables") or []
    if e:
        sp_firs = [r["name"] for r in e[0]["firs"] if r["spoofing"]]
        lines.append(f"- EASA, {e[0]['days']} days to {e[0]['date']}: {len(e[0]['firs'])} FIRs with reports; spoofing marked in {', '.join(sp_firs)}.")
    lines.append("")

    lines += ["## Space", ""]
    if geo:
        c = geo["counts"]
        lines.append(f"- GEO belt ({geo['snapshot_day']}): {c['objects']} active objects, {c['drifting']} drifting, "
                     f"{len(geo['close_other_owner'])} pairs of different owners within 100 km; manoeuvres listed: {len(geo['manoeuvres'])}. "
                     "Proximity, not intent; see docs/validation/geo-board.md for which pairs are inspection, servicing or slot-sharing.")
    if kp:
        rows_kp = [r for r in kp if r["time_tag"][:10] in week]
        if rows_kp:
            mx = max(rows_kp, key=lambda r: r["Kp"])
            t = datetime.fromisoformat(mx["time_tag"]).replace(tzinfo=timezone.utc)
            lines.append(f"- Geomagnetic: Kp maximum {mx['Kp']:.2f} in the 3 hours from {t:%Y-%m-%d %H:%M} UTC ({central(t)}) (NOAA SWPC)"
                         + ("; G1 storm level is Kp 5." if mx["Kp"] < 5 else "."))
    sc = board.get("scintillation")
    if sc:
        lines.append(f"- Ionospheric scintillation (ESA nowcast, {sc['valid_utc']}): {sc['level']}.")
    lines.append("- Sun outages: no season in progress; the next begins in late February 2027 (the /sun calculator gives exact windows).")
    lines.append("")

    if em and em.get("months"):
        m = em["months"][-1]
        lines += ["## Graded events (events v1.0)", "",
                  f"{m['month']} to {em['last_day']}: Multiple sources {m['effect_support']['Multiple sources']:,}, partially corroborated "
                  f"{m['effect_support']['Partially corroborated']:,}, planned {m['effect_verdict']['planned']:,}, benign natural "
                  f"{m['effect_verdict']['benign_natural']:,}, deliberate suspected {m['effect_verdict']['deliberate_suspected']:,}. "
                  "Rules frozen, not yet validated.", ""]

    lines += ["## What this can't see", "",
              "- Aircraft data depend on volunteer feeders: thin over Iran, Iraq and much of Africa; strong jamming removes aircraft from the count.",
              "- Spoofing maps show where receivers were told they were, not where a transmitter is.",
              "- No method here places a transmitter yet; NISAR's first accuracy test against announced US tests is running.", "",
              "## Sources", "",
              "adsb.lol (ODbL 1.0); FAA SPANS (US public domain); Finland's Digitraffic AIS (CC BY 4.0); EASA (source acknowledged); "
              "Swedish Maritime Administration, Traficom and the Estonian Transport Administration (official notices, cited); "
              "USSPACECOM via CelesTrak (basic SSA data, cited); NOAA SWPC (public domain); ESA S2P (data provided by the European "
              "Space Agency as part of its Space Safety Programme, © ESA 2026)."]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--end", help="last UTC day of the week (default: the newest day on the map)")
    ap.add_argument("--out", default=os.path.join(ROOT, "products"))
    a = ap.parse_args()
    end = a.end or ((get("/data/gnss/days.json") or [{}])[-1].get("day"))
    text = draft(end)
    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, f"{end}-weekly-draft.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {path} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
